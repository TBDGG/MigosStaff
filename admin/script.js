const grid = document.getElementById('rules');
const search = document.getElementById('search');
let currentTab = 'frequent';

// Список ID для вкладки "Частые правила"
const frequentIds = ['2.1', '2.2', '2.2.1', '2.10', '3.1.2', '3.8', '3.9', '3.16', '4.3', '4.4', '4.5', '4.6'];

function render(filter = '') {
  const text = filter.toLowerCase();
  let filtered = rules;

  if (currentTab === 'frequent') {
    filtered = filtered.filter(r => frequentIds.includes(r.id));
  }

  if (text) {
    filtered = filtered.filter(r =>
      r.id.includes(text) ||
      r.short.toLowerCase().includes(text) ||
      r.full.toLowerCase().includes(text) ||
      r.punishment.toLowerCase().includes(text)
    );
  }

  // Группировка по секциям и сортировка
  let html = '';
  let lastSection = '';

  filtered.forEach(r => {
    if (r.section !== lastSection) {
      html += `
        <div class="section-divider">
          <span class="section-label">${r.section}</span>
        </div>
      `;
      lastSection = r.section;
    }

    html += `
      <div class="card">
        <div class="rule-id">${r.id}</div>
        <div class="title">${r.short}</div>
        <div class="desc">${r.full}</div>
        <div class="punish">${r.punishment}</div>
      </div>
    `;
  });

  grid.innerHTML = html || '<div style="grid-column: 1/-1; text-align: center; color: #6b4f3a; padding: 40px;">Правила не найдены</div>';
}

function setTab(tab) {
  currentTab = tab;
  document.querySelectorAll('.tab').forEach(b => b.classList.remove('active'));
  
  document.querySelectorAll('.tab').forEach(b => {
    if ((tab === 'frequent' && b.textContent.includes('Частые')) ||
        (tab === 'all' && b.textContent.includes('Все'))) {
      b.classList.add('active');
    }
  });
  
  render(search.value);
}

search.addEventListener('input', () => render(search.value));

